// Package v1alpha1 holds the kubeyard.wutz.dev/v1alpha1 types that the host-mode
// operator reconciles (docs/operator.md §1). The types are plain Go structs with
// JSON tags that match the documented manifests. DeepCopy is written by hand in
// deepcopy.go, because controller-gen is not part of the toolchain yet.
package v1alpha1

import (
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/runtime"
)

// VirtualCluster is the unit of priority, nodes, metering, and kubeconfig.
type VirtualCluster struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`

	Spec   VirtualClusterSpec   `json:"spec,omitempty"`
	Status VirtualClusterStatus `json:"status,omitempty"`
}

// VirtualClusterList is a list of VirtualClusters.
type VirtualClusterList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`

	Items []VirtualCluster `json:"items"`
}

// VirtualClusterSpec is the desired state of a VirtualCluster.
type VirtualClusterSpec struct {
	DisplayName string `json:"displayName,omitempty"`
	Description string `json:"description,omitempty"`
	// Priority orders claims during preemption; a larger value wins.
	Priority int32 `json:"priority"`
	// Preemptible false means the nodes of this VC are never taken for another VC.
	Preemptible bool `json:"preemptible"`
	// Provider is vcluster or k3k.
	Provider string `json:"provider"`
	// Mode is dedicated-nodes in v1.
	Mode    string `json:"mode"`
	Version string `json:"version,omitempty"`
	Distro  string `json:"distro,omitempty"`
	// Exposure is how the control plane is reached from outside the host.
	Exposure Exposure `json:"exposure"`
	// ValuesOverride is passed to the vcluster chart, subject to the webhook allowlist.
	ValuesOverride *runtime.RawExtension `json:"valuesOverride,omitempty"`
	PoolClaims     []PoolClaim           `json:"poolClaims,omitempty"`
}

// ExposureType is how the control plane is exposed.
type ExposureType string

const (
	ExposureLoadBalancer ExposureType = "LoadBalancer"
	ExposureIngress      ExposureType = "Ingress"
)

// Exposure is the external address of the control plane.
type Exposure struct {
	Type           ExposureType     `json:"type"`
	LoadBalancerIP string           `json:"loadBalancerIP,omitempty"`
	Ingress        *IngressExposure `json:"ingress,omitempty"`
}

// IngressExposure is the host and port used when Exposure.Type is Ingress.
type IngressExposure struct {
	Host string `json:"host"`
	Port int32  `json:"port"`
}

// PoolClaim is one virtual cluster's claim on a NodePool.
type PoolClaim struct {
	Pool string `json:"pool"`
	// Min is the guaranteed count; it is never preempted.
	Min int32 `json:"min"`
	// Max caps both scale-up and preemption.
	Max int32 `json:"max"`
	// Desired is the target count when Autoscale is not enabled.
	Desired   int32      `json:"desired"`
	Autoscale *Autoscale `json:"autoscale,omitempty"`
	// PinnedNodes are chosen by an administrator and count toward Min.
	PinnedNodes []string `json:"pinnedNodes,omitempty"`
}

// Autoscale drives the claim from pending pods.
type Autoscale struct {
	Enabled bool `json:"enabled"`
	// ScaleDownIdle is how long a node must be idle before it is released.
	ScaleDownIdle *metav1.Duration `json:"scaleDownIdle,omitempty"`
}

// VirtualClusterPhase is the lifecycle phase of a VirtualCluster.
type VirtualClusterPhase string

const (
	VirtualClusterPending      VirtualClusterPhase = "Pending"
	VirtualClusterProvisioning VirtualClusterPhase = "Provisioning"
	VirtualClusterReady        VirtualClusterPhase = "Ready"
	VirtualClusterDegraded     VirtualClusterPhase = "Degraded"
	VirtualClusterDraining     VirtualClusterPhase = "Draining"
	VirtualClusterDeleting     VirtualClusterPhase = "Deleting"
)

// VirtualClusterStatus is the observed state of a VirtualCluster.
type VirtualClusterStatus struct {
	Phase         VirtualClusterPhase `json:"phase,omitempty"`
	HostNamespace string              `json:"hostNamespace,omitempty"`
	Endpoint      string              `json:"endpoint,omitempty"`
	// AdminKubeconfigSecretRef points to the admin kubeconfig generated by vcluster.
	AdminKubeconfigSecretRef *SecretReference   `json:"adminKubeconfigSecretRef,omitempty"`
	Allocations              []PoolAllocation   `json:"allocations,omitempty"`
	Conditions               []metav1.Condition `json:"conditions,omitempty"`
}

// SecretReference names a key in a Secret.
type SecretReference struct {
	Namespace string `json:"namespace"`
	Name      string `json:"name"`
	Key       string `json:"key"`
}

// PoolAllocation lists the nodes a VirtualCluster holds in one pool.
type PoolAllocation struct {
	Pool  string   `json:"pool"`
	Nodes []string `json:"nodes,omitempty"`
	// PendingDemand is the extra nodes that autoscale observed as needed.
	PendingDemand int32 `json:"pendingDemand,omitempty"`
}

// NodePool is a class of nodes that virtual clusters can claim.
type NodePool struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`

	Spec   NodePoolSpec   `json:"spec,omitempty"`
	Status NodePoolStatus `json:"status,omitempty"`
}

// NodePoolList is a list of NodePools.
type NodePoolList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`

	Items []NodePool `json:"items"`
}

// NodePoolSpec selects the candidate nodes and the preemption rules.
type NodePoolSpec struct {
	DisplayName string `json:"displayName,omitempty"`
	// NodeSelector picks the candidate nodes, usually by NFD or GPU labels.
	NodeSelector metav1.LabelSelector `json:"nodeSelector"`
	Preemption   PreemptionSpec       `json:"preemption,omitempty"`
	Release      ReleaseSpec          `json:"release,omitempty"`
}

// PreemptionPolicy says whether claims may take nodes from lower-priority claims.
type PreemptionPolicy string

const (
	PreemptionNever         PreemptionPolicy = "Never"
	PreemptionLowerPriority PreemptionPolicy = "LowerPriority"
)

// PreemptionSpec sets the drain timing for preempted nodes.
type PreemptionSpec struct {
	Policy PreemptionPolicy `json:"policy,omitempty"`
	// GracePeriod is how long the victim is told before its pods are evicted.
	GracePeriod *metav1.Duration `json:"gracePeriod,omitempty"`
	// DrainTimeout is when the drain is forced.
	DrainTimeout *metav1.Duration `json:"drainTimeout,omitempty"`
}

// ReleaseSpec describes what happens to a node when it is released.
type ReleaseSpec struct {
	// Wipe is none or reboot.
	Wipe string `json:"wipe,omitempty"`
}

// NodePoolStatus counts the nodes that the pool's selector matches.
type NodePoolStatus struct {
	Total     int32 `json:"total"`
	Free      int32 `json:"free"`
	Reserved  int32 `json:"reserved"`
	Unhealthy int32 `json:"unhealthy"`
}

// NodeLease is the single source of truth for which VirtualCluster holds a node.
// Its name is the node name, so a node has at most one active lease.
type NodeLease struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`

	Spec   NodeLeaseSpec   `json:"spec,omitempty"`
	Status NodeLeaseStatus `json:"status,omitempty"`
}

// NodeLeaseList is a list of NodeLeases.
type NodeLeaseList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`

	Items []NodeLease `json:"items"`
}

// LeaseReason says why a node was given to a VirtualCluster.
type LeaseReason string

const (
	LeasePinned  LeaseReason = "Pinned"
	LeaseMin     LeaseReason = "Min"
	LeaseScale   LeaseReason = "Scale"
	LeasePreempt LeaseReason = "Preempt"
)

// NodeLeaseSpec names the node, its pool, and the VirtualCluster that holds it.
type NodeLeaseSpec struct {
	Node           string      `json:"node"`
	Pool           string      `json:"pool"`
	VirtualCluster string      `json:"virtualCluster"`
	Reason         LeaseReason `json:"reason,omitempty"`
}

// LeasePhase is the lifecycle phase of a NodeLease.
type LeasePhase string

const (
	LeaseBinding  LeasePhase = "Binding"
	LeaseBound    LeasePhase = "Bound"
	LeaseDraining LeasePhase = "Draining"
	LeaseReleased LeasePhase = "Released"
)

// NodeLeaseStatus is the observed state of a NodeLease.
type NodeLeaseStatus struct {
	Phase         LeasePhase   `json:"phase,omitempty"`
	BoundAt       *metav1.Time `json:"boundAt,omitempty"`
	DrainDeadline *metav1.Time `json:"drainDeadline,omitempty"`
	// IdleSince is when the node was first seen with no workload of its
	// VirtualCluster, while that VirtualCluster autoscales. Set only while idle.
	IdleSince *metav1.Time `json:"idleSince,omitempty"`
}
